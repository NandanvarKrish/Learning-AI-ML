# STRING METHODS

text = " Hello, World "
print(text.strip()) # Remove unwanted whitespace
print(text.upper()) # Changes text to Uppercase
print(text.lower()) # Changes text to Lowercase
print(text.replace("World", "AI")) # Replace the selected part of string
print(text.split(", ")) # Splits the string from the selected part
print("World" in text) # Checks whether the word is exist in string or not
print(len(text)) # Prints the length of string
